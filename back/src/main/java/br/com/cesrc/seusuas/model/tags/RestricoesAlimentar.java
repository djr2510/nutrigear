package br.com.cesrc.seusuas.model.tags;

/**
 * Enumeração que representa as restrições alimentares.
 *
 * Esta enumeração define as restrições alimentares que podem ser associadas a uma pessoa ou receita,
 * como glúten, lactose, açúcar, frutos do mar, nozes, amendoim, ovo, soja e baixo sódio.
 */
public enum RestricoesAlimentar {

    /**
     * Restrição a glúten.
     */
    GLUTEN,

    /**
     * Restrição a lactose.
     */
    LACTOSE,

    /**
     * Restrição a açúcar.
     */
    ACUCAR,

    /**
     * Restrição a frutos do mar.
     */
    FRUTOS_DO_MAR,

    /**
     * Restrição a nozes.
     */
    NOZES,

    /**
     * Restrição a amendoim.
     */
    AMENDOIM,

    /**
     * Restrição a ovo.
     */
    OVO,

    /**
     * Restrição a soja.
     */
    SOJA,

    /**
     * Restrição a baixo sódio.
     */
    BAIXO_SODIO
}