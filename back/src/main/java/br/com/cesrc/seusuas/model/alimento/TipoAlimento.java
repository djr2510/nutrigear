package br.com.cesrc.seusuas.model.alimento;

/**
 * Enumeração que representa os tipos de alimentos.
 *
 * Esta enumeração define os tipos de alimentos que podem ser associados a um AlimentoModel.
 */
public enum TipoAlimento {

    /**
     * Representa alimentos de origem vegetal.
     */
    VEGETAL,

    /**
     * Representa frutas.
     */
    FRUTA,

    /**
     * Representa carnes.
     */
    CARNE,

    /**
     * Representa alimentos processados.
     */
    PROCESSADO,

    /**
     * Representa líquidos.
     */
    LIQUIDO,

    /**
     * Representa cereais e grãos.
     */
    CEREAL,

    /**
     * Representa laticínios.
     */
    LATICINIO,

    /**
     * Representa oleaginosas e sementes.
     */
    OLEAGINOSA,

    /**
     * Representa leguminosas como feijão, lentilha e grão-de-bico.
     */
    LEGUMINOSA,

    /**
     * Representa temperos e ervas.
     */
    TEMPERO
}
