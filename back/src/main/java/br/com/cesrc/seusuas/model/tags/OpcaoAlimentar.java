package br.com.cesrc.seusuas.model.tags;

/**
 * Enumeração que representa as opções alimentares.
 *
 * Esta enumeração define as opções alimentares que podem ser associadas a uma pessoa ou receita,
 * como vegetariano, vegano, halal, kosher, sem laticínios, sem ovos e pescatariano.
 */
public enum OpcaoAlimentar {

    /**
     * Opção alimentar vegetariana.
     */
    VEGETARIANO,

    /**
     * Opção alimentar vegana.
     */
    VEGANO,

    /**
     * Opção alimentar halal.
     */
    HALAL,

    /**
     * Opção alimentar kosher.
     */
    KOSHER,

    /**
     * Opção alimentar sem laticínios.
     */
    SEM_LATICINIOS,

    /**
     * Opção alimentar sem ovos.
     */
    SEM_OVOS,

    /**
     * Opção alimentar pescatariana.
     */
    PESCATARIANO
}